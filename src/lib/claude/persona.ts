/** 投稿にできる要素がそろったとパートナーが判断したときに、返事の最後に付ける印。画面には出さない（段なしの古い形。台本が使う） */
export const READY_MARK = "[[とどけられる]]";

/** とどけるの段。1＝何があったか、2＝どうしたか・どうなったか、3＝誰の役に立つかまで言葉になった */
export type ReadyLevel = 1 | 2 | 3;

/** 段つきの印。本物のパートナーはこの形で返事の最後に付ける */
export function readyMark(level: ReadyLevel): string {
  return `[[とどけられる:${level}]]`;
}

/** 調べものの出典の印。Web 検索で調べた返事の最後に、出典ごとに1つずつ付く。画面は取り除いてリンクにし、声では読まない */
export function sourceMark(title: string, url: string): string {
  return `[[出典:${title.replace(/[|\]\n]/g, " ").trim()}|${url}]]`;
}

